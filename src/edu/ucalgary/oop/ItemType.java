/**
 * Defines the types of items that can be managed in the disaster management system.
 * Each type represents a different category of supplies or belongings that can be
 * allocated to disaster victims or locations.
 *
 * @author University of Calgary OOP Team
 * @version 1.0
 * @since 2024-03-20
 */
package edu.ucalgary.oop;

public enum ItemType {
    /** Water supplies for drinking and hygiene */
    WATER,
    
    /** Cots for sleeping arrangements */
    COT,
    
    /** Blankets for warmth and comfort */
    BLANKET,
    
    /** Personal belongings of disaster victims */
    PERSONAL_BELONGING,
    
    /** Clothing items for disaster victims */
    CLOTHING,
    
    /** Food supplies for disaster victims */
    FOOD
} 